import numpy as np
from sklearn.metrics import accuracy_score, confusion_matrix, classification_report, roc_curve, auc
from sklearn.metrics import f1_score

def evaluate_model(model, x_test, y_test_cat):
    # Make predictions on the test set
    pred_class_test_prob = model.predict(x_test)
    pred_class_test = np.argmax(pred_class_test_prob, axis=1)

    # Convert y_test_cat back to class labels
    y_test_labels = np.argmax(y_test_cat, axis=1)

    # Evaluate the classification model
    accuracy = accuracy_score(y_test_labels, pred_class_test)
    print(f'Classification Accuracy: {accuracy:.4f}')

    # Confusion Matrix
    cm = confusion_matrix(y_test_labels, pred_class_test)
    print("Confusion Matrix:")
    print(cm)

    # Classification Report
    print("\nClassification Report:")
    print(classification_report(y_test_labels, pred_class_test, target_names=['AD', 'AO', 'AL']))

    # F1 Score (macro average)
    f1 = f1_score(y_test_labels, pred_class_test, average='macro')
    print(f"\nF1 Score (macro): {f1:.4f}")

    # ROC Curve and AUC for each class
    n_classes = 3
    fpr = dict()
    tpr = dict()
    roc_auc = dict()
    for i in range(n_classes):
        fpr[i], tpr[i], _ = roc_curve(y_test_cat[:, i], pred_class_test_prob[:, i])
        roc_auc[i] = auc(fpr[i], tpr[i])

    # Print AUC for each class
    for i in range(n_classes):
        print(f"AUC for class {i}: {roc_auc[i]:.4f}")

    import seaborn as sns

    # Confusion matrix heatmap
    plt.figure(figsize=(10, 8))
    sns.heatmap(cm, annot=True, fmt='d', cmap='Blues')
    plt.xlabel('Predicted')
    plt.ylabel('Actual')
    plt.title('Confusion Matrix')
    plt.show()

    return accuracy, cm, f1, roc_auc

