def convert_to_categories(y):
    categories = []
    for value in y:
        if value < 40:
            categories.append(0)  # AD
        elif 40 <= value <= 60:
            categories.append(1)  # AO
        else:
            categories.append(2)  # AL
    return np.array(categories)

